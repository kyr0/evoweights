/**
 * Page zoom for the built site: the page renders at 150 %, the way Chrome renders it after ctrl+ to 150 %.
 *
 * Why CSS zoom plus a build step rather than rescaling the sources: a page cannot set the browser's zoom, and scaling
 * every length by hand would touch the vendored defuss-shadcn sheets and force every later edit to use scaled sizes.
 * The build writes ROOT_CSS, which sets `zoom` on the root; that scales every length and reflows the layout. The
 * differences from browser zoom that live in CSS are corrected here:
 * - VERIFIED (Chromium 156): media queries ignore CSS zoom. Browser zoom narrows the viewport in CSS pixels, so a
 *   breakpoint B applies up to a window of B × zoom pixels: width and height thresholds are scaled by the zoom.
 * - VERIFIED (Chromium 156): viewport units are zoomed a second time (`100vw` measured 1800 px in a 1200 px window,
 *   `100vh` 1200 px in an 800 px one). Browser zoom keeps 1vw at 1 % of the window: viewport lengths are divided.
 * - VERIFIED: `devicePixelRatio` stays 1 and `getBoundingClientRect` reports zoomed sizes; the scripts that depend on
 *   them correct for `currentCSSZoom` themselves (src/app/hero-evolution.ts, src/app/revisions-panel.ts).
 *
 * VERIFIED: phones keep 100 %. At 150 % a 390 px phone would lay out at 260 px, where the site overflows (335 px of
 * content). Zoom therefore starts at MIN_LAYOUT_WIDTH × PAGE_ZOOM, and every scaled media query keeps its original form
 * for narrower windows.
 */
export const PAGE_ZOOM = 1.5;
/** The narrowest layout width the site is tested at (tests/e2e: 390 px). */
export const MIN_LAYOUT_WIDTH = 390;
/** Windows from this width up are zoomed; below it the layout would drop under MIN_LAYOUT_WIDTH. */
export const ZOOM_MIN_WIDTH = MIN_LAYOUT_WIDTH * PAGE_ZOOM;

// Range syntax leaves no gap at fractional window widths, where max-width 584.98px would.
const BELOW_ZOOM = `(width < ${ZOOM_MIN_WIDTH}px)`;
const FROM_ZOOM = `(min-width: ${ZOOM_MIN_WIDTH}px)`;
// Browser zoom narrows the viewport in both directions, so height thresholds scale like widths; ratios carry no unit.
const SIZE_FEATURE = /\b(?:width|height)\b/i;
const LENGTH = /(\d*\.?\d+)(px|rem|em)\b/g;
const TOKEN =
  /\/\*[\s\S]*?\*\/|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|\burl\([^)]*\)|@media\b([^{]*)\{|(?<![\w.#-])(-?(?:\d+\.?\d*|\.\d+))(vw|vh|vmin|vmax|svw|svh|lvw|lvh|dvw|dvh)(?![\w-])/g;

/** Where the build writes ROOT_CSS, relative to docs/; the page links it before every other stylesheet. */
export const ROOT_CSS_PATH = 'styles/page-zoom.css';
export const ROOT_CSS = `/* Generated by scripts/build.ts from scripts/page-zoom.ts: the page renders at ${PAGE_ZOOM * 100} %. */
:root { --page-zoom: 1; }
@media ${FROM_ZOOM} { :root { --page-zoom: ${PAGE_ZOOM}; } }
html { zoom: var(--page-zoom); }
`;

function round(value: number): string {
  return String(Math.round(value * 1000) / 1000);
}

/** Split a media query list on its top-level commas. */
function queries(prelude: string): string[] {
  const parts: string[] = [];
  let depth = 0,
    start = 0;
  for (let i = 0; i < prelude.length; i++) {
    const c = prelude[i];
    if (c === '(') depth++;
    else if (c === ')') depth--;
    else if (c === ',' && depth === 0) {
      parts.push(prelude.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(prelude.slice(start));
  return parts.map((q) => q.trim()).filter(Boolean);
}

/** One media query becomes its zoomed form (from ZOOM_MIN_WIDTH up) plus its original form (below it). */
function zoomQuery(query: string): string[] {
  if (!SIZE_FEATURE.test(query)) return [query];
  if (/^not\b/i.test(query)) throw new Error(`page zoom cannot rewrite a negated size query: @media ${query}`);
  const zoomed = query.replace(LENGTH, (_, n: string, unit: string) => round(Number(n) * PAGE_ZOOM) + unit);
  return [`${zoomed} and ${FROM_ZOOM}`, `${query} and ${BELOW_ZOOM}`];
}

/** Rewrite one stylesheet so that, under the root `zoom` of page-zoom.css, it renders like browser zoom. */
export function zoomCss(css: string): string {
  return css.replace(TOKEN, (match: string, prelude?: string, number?: string, unit?: string) => {
    if (prelude !== undefined) {
      if (!SIZE_FEATURE.test(prelude)) return match;
      return '@media ' + queries(prelude).flatMap(zoomQuery).join(', ') + ' {';
    }
    if (number !== undefined) return `calc(${number}${unit} / var(--page-zoom, 1))`;
    return match; // comments, strings and url() stay as written
  });
}
